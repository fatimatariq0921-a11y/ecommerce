export const products = Object.entries(categoriesMeta).flatMap(
  ([category, names]) =>
    names.map((name, idx) => {
      const price = 20 + ((idx + 1) * 7) % 220

      return {
        id: id++,
        name,
        category,
        price,
        originalPrice: Math.round(price * 1.3),
        rating: Number((4 + ((idx % 10) / 10)).toFixed(1)),
        reviews: 50 + idx * 14,
        image: getImage(category, idx),
      }
    }),
)

